async function main() {
  let updated = 0;
  let skipped = 0;
  for (const [id, images] of Object.entries(imageMap)) {
    try {
      const product = await prisma.product.findUnique({ where: { id }, select: { id: true, images: true } });
      if (!product) { skipped++; continue; }
      const currentFirst = Array.isArray(product.images) ? product.images[0] : null;
      const correctFirst = images[0];
      if (currentFirst === correctFirst) { skipped++; continue; }
      await prisma.product.update({ where: { id }, data: { images } });
      updated++;
      console.log(`Updated: ${id}`);
    } catch (e) {
      console.error(`Failed: ${id} - ${e.message}`);
    }
  }
  console.log(`\nDone. Updated: ${updated}, Skipped: ${skipped}`);
  await prisma.$disconnect();
}

main();
